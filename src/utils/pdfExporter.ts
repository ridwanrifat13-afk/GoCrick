import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import { TournamentState, ALL_GROUPS, InningsData } from '../types/tournament';
import { formatOvers, calculateRunRate } from './tournamentReducer';
import { GROUP_DESCRIPTIONS } from '../data/initialTournamentState';

export function exportSquadsPDF(state: TournamentState): void {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });

  // Header Banner
  doc.setFillColor(11, 17, 30);
  doc.rect(0, 0, 210, 34, 'F');

  doc.setTextColor(16, 185, 129);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.text('OFFICIAL TOURNAMENT DRAFT & SQUAD ARCHIVE', 14, 11);

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(18);
  doc.text(state.title, 14, 20);

  doc.setTextColor(203, 213, 225);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.text(
    `Tournament Date: ${state.date}  |  Venue: ${state.venue}  |  24 Players (3 Captains + Groups A-G)`,
    14,
    28
  );

  let currentY = 42;

  // Section 1: 3 Formed Teams
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text('1. Official Team Squads (3 Teams x 8 Players)', 14, currentY);
  currentY += 4;

  for (const team of state.teams) {
    const captain = state.players.find((p) => p.id === team.captainId);
    const drafted = ALL_GROUPS.map((g) => {
      const p = state.players.find((pl) => pl.group === g && pl.assignedTeamId === team.id);
      return [
        `Group ${g}`,
        GROUP_DESCRIPTIONS[g],
        p ? p.name : 'Pending Shuffle',
        p ? p.role : '-',
      ];
    });

    const rows = [
      [
        'CAPTAIN',
        'Team Captain & Leader',
        `${team.captainName} (C)`,
        captain?.role || 'All-Rounder',
      ],
      ...drafted,
    ];

    autoTable(doc, {
      startY: currentY + 2,
      head: [[`${team.name} (${team.shortName})`, 'Performance Tier', 'Player Name', 'Role']],
      body: rows,
      theme: 'grid',
      headStyles: {
        fillColor: [19, 28, 46],
        textColor: [255, 255, 255],
        fontStyle: 'bold',
        fontSize: 9.5,
      },
      bodyStyles: {
        fontSize: 8.5,
        textColor: [30, 41, 59],
      },
      columnStyles: {
        0: { cellWidth: 28, fontStyle: 'bold' },
        1: { cellWidth: 62 },
        2: { cellWidth: 62, fontStyle: 'bold' },
        3: { cellWidth: 30 },
      },
      margin: { left: 14, right: 14 },
    });

    const finalY = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY || currentY + 45;
    currentY = finalY + 6;
  }

  // Page 2: Complete Group A-G Categorisation Record
  doc.addPage();
  doc.setFillColor(11, 17, 30);
  doc.rect(0, 0, 210, 24, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.text(`${state.title} — Group A to G Categorisation`, 14, 15);

  const groupRows: string[][] = [];
  for (const g of ALL_GROUPS) {
    const groupPlayers = state.players.filter((p) => p.group === g);
    groupPlayers.forEach((p, idx) => {
      const assignedTeam = state.teams.find((t) => t.id === p.assignedTeamId);
      groupRows.push([
        idx === 0 ? `Group ${g}` : '',
        idx === 0 ? GROUP_DESCRIPTIONS[g] : '',
        p.name,
        p.role,
        assignedTeam ? `${assignedTeam.name} (${assignedTeam.shortName})` : 'Unassigned',
      ]);
    });
  }

  autoTable(doc, {
    startY: 32,
    head: [['Group', 'Performance Tier Category', 'Player Name', 'Role', 'Drafted To Team']],
    body: groupRows,
    theme: 'striped',
    headStyles: {
      fillColor: [16, 185, 129],
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 9,
    },
    bodyStyles: {
      fontSize: 8.5,
      textColor: [15, 23, 42],
    },
    margin: { left: 14, right: 14 },
  });

  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(100, 116, 139);
    doc.text(
      `Generated by SGHS-23 Cricket Tournament Season 2 Live Platform  •  Page ${i} of ${pageCount}`,
      14,
      290
    );
  }

  doc.save(`SGHS23_Season2_Squads_${state.date}.pdf`);
}

function buildInningsTables(state: TournamentState, inn: InningsData) {
  const battingRows: string[][] = [];
  const batterIds = new Set<string>();

  for (const b of inn.ballLog) {
    batterIds.add(b.strikerId);
    batterIds.add(b.nonStrikerId);
  }
  if (inn.strikerId) batterIds.add(inn.strikerId);
  if (inn.nonStrikerId) batterIds.add(inn.nonStrikerId);

  for (const bId of batterIds) {
    const player = state.players.find((p) => p.id === bId);
    if (!player) continue;

    const facedBalls = inn.ballLog.filter((b) => b.strikerId === bId && b.extraType !== 'WD');
    const runs = inn.ballLog
      .filter((b) => b.strikerId === bId)
      .reduce((sum, b) => sum + b.runsOffBat, 0);
    const fours = inn.ballLog.filter((b) => b.strikerId === bId && b.runsOffBat === 4).length;
    const sixes = inn.ballLog.filter((b) => b.strikerId === bId && b.runsOffBat === 6).length;
    const sr = facedBalls.length > 0 ? ((runs / facedBalls.length) * 100).toFixed(1) : '0.0';

    const dismissalBall = inn.ballLog.find(
      (b) => b.isWicket && (b.dismissedPlayerId || b.strikerId) === bId
    );
    let dismissalText = 'not out';
    if (dismissalBall) {
      const bowler = state.players.find((p) => p.id === dismissalBall.bowlerId)?.name || 'Bowler';
      dismissalText = `${dismissalBall.wicketType || 'Out'}${
        dismissalBall.fielderName ? ` (${dismissalBall.fielderName})` : ''
      } b ${bowler}`;
    } else if (bId === inn.strikerId || bId === inn.nonStrikerId) {
      dismissalText = 'not out *';
    }

    battingRows.push([
      player.name,
      dismissalText,
      String(runs),
      String(facedBalls.length),
      String(fours),
      String(sixes),
      sr,
    ]);
  }

  const bowlerIds = new Set<string>();
  for (const b of inn.ballLog) {
    bowlerIds.add(b.bowlerId);
  }
  if (inn.currentBowlerId) bowlerIds.add(inn.currentBowlerId);

  const bowlingRows: string[][] = [];
  for (const bwId of bowlerIds) {
    const player = state.players.find((p) => p.id === bwId);
    if (!player) continue;

    const deliveries = inn.ballLog.filter((b) => b.bowlerId === bwId);
    const legalBalls = deliveries.filter((b) => b.isLegalDelivery).length;
    const runsConceded = deliveries.reduce(
      (sum, b) => sum + (b.extraType === 'BYE' || b.extraType === 'LB' ? 0 : b.totalRuns),
      0
    );
    const wickets = deliveries.filter(
      (b) => b.isWicket && b.wicketType !== 'Run Out'
    ).length;
    const econ = legalBalls > 0 ? ((runsConceded / legalBalls) * 6).toFixed(2) : '0.00';

    bowlingRows.push([
      player.name,
      formatOvers(legalBalls),
      String(runsConceded),
      String(wickets),
      econ,
    ]);
  }

  return { battingRows, bowlingRows };
}

export function exportMatchScorecardPDF(state: TournamentState, matchId: string): void {
  const match = state.matches.find((m) => m.id === matchId);
  if (!match) return;

  const teamA = state.teams.find((t) => t.id === match.teamAId);
  const teamB = state.teams.find((t) => t.id === match.teamBId);

  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });

  // Header
  doc.setFillColor(11, 17, 30);
  doc.rect(0, 0, 210, 38, 'F');

  doc.setTextColor(16, 185, 129);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9.5);
  doc.text(`${state.title.toUpperCase()}  •  OFFICIAL MATCH SCORECARD`, 14, 10);

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(16);
  doc.text(`${match.title}: ${teamA?.name || 'Team 1'} vs ${teamB?.name || 'Team 2'}`, 14, 19);

  doc.setTextColor(203, 213, 225);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.text(
    `${match.scheduledTime}  |  Venue: ${match.venue}  |  Format: ${match.oversLimit} Overs`,
    14,
    26
  );

  doc.setTextColor(245, 158, 11);
  doc.setFont('helvetica', 'bold');
  doc.text(
    match.resultSummary || `Match Status: ${match.status.toUpperCase()}`,
    14,
    33
  );

  let currentY = 45;

  const renderInningsSection = (inn: InningsData, label: string) => {
    const batTeam = state.teams.find((t) => t.id === inn.battingTeamId);
    const totalExtras =
      inn.extras.wides + inn.extras.noBalls + inn.extras.byes + inn.extras.legByes;
    const { battingRows, bowlingRows } = buildInningsTables(state, inn);

    doc.setTextColor(15, 23, 42);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11.5);
    doc.text(
      `${label}: ${batTeam?.name || 'Batting Team'} — ${inn.runs}/${inn.wickets} (${formatOvers(
        inn.legalBalls
      )} / ${match.oversLimit} Overs, CRR: ${calculateRunRate(inn.runs, inn.legalBalls)})`,
      14,
      currentY
    );

    autoTable(doc, {
      startY: currentY + 3,
      head: [['Batter', 'Dismissal', 'R', 'B', '4s', '6s', 'SR']],
      body:
        battingRows.length > 0
          ? battingRows
          : [['No deliveries recorded yet', '-', '0', '0', '0', '0', '0.0']],
      theme: 'grid',
      headStyles: {
        fillColor: [19, 28, 46],
        textColor: [255, 255, 255],
        fontSize: 8.5,
      },
      bodyStyles: {
        fontSize: 8,
      },
      margin: { left: 14, right: 14 },
    });

    currentY =
      ((doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ||
        currentY + 25) + 4;

    doc.setFontSize(8.5);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(51, 65, 85);
    doc.text(
      `Extras: ${totalExtras} (WD: ${inn.extras.wides}, NB: ${inn.extras.noBalls}, B: ${inn.extras.byes}, LB: ${inn.extras.legByes})`,
      14,
      currentY
    );
    currentY += 3;

    autoTable(doc, {
      startY: currentY,
      head: [['Bowler', 'Overs', 'Runs', 'Wickets', 'Economy']],
      body:
        bowlingRows.length > 0
          ? bowlingRows
          : [['No overs bowled yet', '0.0', '0', '0', '0.00']],
      theme: 'striped',
      headStyles: {
        fillColor: [51, 65, 85],
        textColor: [255, 255, 255],
        fontSize: 8.5,
      },
      bodyStyles: {
        fontSize: 8,
      },
      margin: { left: 14, right: 14 },
    });

    currentY =
      ((doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ||
        currentY + 25) + 8;
  };

  renderInningsSection(match.innings1, '1st Innings');

  if (currentY > 210) {
    doc.addPage();
    currentY = 20;
  }

  renderInningsSection(match.innings2, '2nd Innings');

  // Key Ball-by-Ball Commentary Log
  const allBalls = [...match.innings1.ballLog, ...match.innings2.ballLog];
  if (allBalls.length > 0) {
    if (currentY > 220) {
      doc.addPage();
      currentY = 20;
    }
    doc.setTextColor(15, 23, 42);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.text('Ball-by-Ball Commentary Archive (Recent & Highlight Deliveries)', 14, currentY);

    const commRows = allBalls.slice(-18).reverse().map((b) => [
      `Inn ${b.inningsNumber} • ${b.overBallLabel}`,
      b.isWicket ? 'WICKET' : b.runsOffBat === 6 ? 'SIX (6)' : b.runsOffBat === 4 ? 'FOUR (4)' : `${b.totalRuns} run(s)`,
      b.commentary,
    ]);

    autoTable(doc, {
      startY: currentY + 3,
      head: [['Over', 'Event', 'Commentary']],
      body: commRows,
      theme: 'grid',
      headStyles: {
        fillColor: [16, 185, 129],
        textColor: [255, 255, 255],
        fontSize: 8.5,
      },
      bodyStyles: {
        fontSize: 7.5,
      },
      columnStyles: {
        0: { cellWidth: 24, fontStyle: 'bold' },
        1: { cellWidth: 26, fontStyle: 'bold' },
        2: { cellWidth: 132 },
      },
      margin: { left: 14, right: 14 },
    });
  }

  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(100, 116, 139);
    doc.text(
      `SGHS-23 Cricket Tournament season 2 Official Scorecard Archive  •  Page ${i} of ${pageCount}`,
      14,
      290
    );
  }

  doc.save(`SGHS23_Season2_Scorecard_Match${match.matchNumber}.pdf`);
}
